"""Regenerate src/spec_vectors_test.mbt from the examples on the JSON-RPC 2.0 specification page.

Every `-->` and `<--` pair in its section 7 becomes one case, so a change on the page shows up as a
diff here rather than as a test nobody compared.
"""
import html
import pathlib
import re
import sys
import urllib.request

URL = "https://www.jsonrpc.org/specification"
ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "src/spec_vectors_test.mbt"
EXPECTED = 15

request = urllib.request.Request(URL, headers={"User-Agent": "moonjrpc-vectors"})
page = urllib.request.urlopen(request, timeout=60).read().decode()
section = page[page.index('id="examples"') : page.index('id="extensions"')]
blocks = [
    html.unescape(re.sub(r"<[^>]+>", "", re.sub(r"<br\s*/?>", "\n", block)))
    for block in re.findall(r"<pre[^>]*>(.*?)</pre>", section, re.S)
]
cases = []
for block in blocks:
    parts = re.split(r"(-->|<--)", block)
    pending = None
    for mark, text in zip(parts[1::2], parts[2::2]):
        text = text.strip()
        if text.startswith("data sent"):
            continue
        if mark == "-->":
            if pending is not None:
                cases.append((pending, None))
            pending = text
        else:
            cases.append((pending, None if text.startswith("//") else text))
            pending = None
    if pending is not None:
        cases.append((pending, None))
if len(cases) != EXPECTED:
    sys.exit(f"found {len(cases)} cases, wanted {EXPECTED}: the page has changed")


def raw(text, indent):
    return "\n".join(f"{indent}#|{line}" for line in text.split("\n"))


out = [
    f"// Generated by scripts/vectors/gen_spec_vectors.py from {URL}, section 7. Do not edit.",
    "",
    "///|",
    "let spec_cases : Array[(String, String?)] = [",
]
for ask, answer in cases:
    out.append("  (")
    out.append("    (")
    out.append(raw(ask, "      "))
    out.append("    ),")
    if answer is None:
        out.append("    None,")
    else:
        out.append("    Some(")
        out.append("      (")
        out.append(raw(answer, "        "))
        out.append("      ),")
        out.append("    ),")
    out.append("  ),")
out.append("]")
OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print(len(cases), "cases")
